// =========================================================
// GET CURRENT LANGUAGE
// =========================================================

function getCurrentLanguage() {
    return localStorage.getItem("language") || "en";
}


// =========================================================
// GET PROJECT TRANSLATION
// =========================================================

function getProjectTranslation(projectId, project) {

    const language = getCurrentLanguage();

    // Get the translated project from projectsTranslations
    const translatedProject =
        projectsTranslations?.[language]?.[projectId];

    // If a translation exists, merge it with the original project
    // so untranslated properties are still available.
    if (translatedProject) {
        return {
            ...project,
            ...translatedProject
        };
    }

    // Fallback to the original project
    return project;
}


// =========================================================
// OPEN POPUP
// =========================================================

document.addEventListener("click", (e) => {

    const card = e.target.closest(
        ".project-card, .identity-card, .illustration-card, .book-card"
    );

    if (!card) return;

    const projectId = card.dataset.project;

    const project = projects[projectId];

    if (!project) return;

    // Get project content in the current language
    const translatedProject =
        getProjectTranslation(projectId, project);

    // Create popup
    popupBody.innerHTML =
        createProjectHTML(
            translatedProject,
            projectId
        );

    popup.classList.add("active");

    document.body.style.overflow = "hidden";


    // =====================================================
    // RESET SCROLL POSITION
    // =====================================================

    requestAnimationFrame(() => {

        const container =
            popup.querySelector(".popup-content");

        if (container) {
            container.scrollTop = 0;
        }

    });

});


// =========================================================
// CLOSE FUNCTION
// =========================================================

function closeProjectPopup() {

    popup.classList.remove("active");

    document.body.style.overflow = "";
}


// =========================================================
// CLOSE BUTTON
// =========================================================

closePopup.addEventListener(
    "click",
    closeProjectPopup
);


// =========================================================
// CLOSE BACKDROP
// =========================================================

popup.addEventListener("click", (e) => {

    if (
        e.target.classList.contains(
            "popup-backdrop"
        )
    ) {

        closeProjectPopup();

    }

});


